export function permissionForAdminPath(pathname: string): PermissionCode | null {
  const match = Object.entries(ADMIN_ROUTE_PERMISSIONS).sort(([a],[b])=>b.length-a.length)
    .find(([path]) => pathname === path || pathname.startsWith(`${path}/`));
  return match?.[1] ?? null;
}

export function hasPermission(permissions: readonly PermissionCode[], required: PermissionCode): boolean {
  return permissions.includes(required);
}

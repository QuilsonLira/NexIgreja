export type PermissionCode = (typeof PERMISSION_DEFINITIONS)[number]["code"];
export const PERMISSION_CODES = PERMISSION_DEFINITIONS.map((item) => item.code) as PermissionCode[];

export function isPermissionCode(value: unknown): value is PermissionCode {
  return typeof value === "string" && PERMISSION_CODES.includes(value as PermissionCode);
}

